_names: list[str] | None = None
_by_name: dict[str, int] | None = None


def _table() -> tuple[list[str], dict[str, int]]:
    """Split the name blob once, on first use."""
    global _names, _by_name
    if _names is None or _by_name is None:
        _names = _NAMES.split()
        _by_name = {name: index for index, name in enumerate(_names)}
    return _names, _by_name


def rgb_for_index(index: int) -> tuple[float, float, float] | None:
    """Return the ``(r, g, b)`` for a built-in colour index, or ``None``.

    Parameters
    ----------
    index : int
        A PyMOL colour index. Session-local colours (``>= COUNT``) and the
        negative :data:`SPECIAL` values are not in this table and return
        ``None``, which is the caller's cue to resolve them itself.

    Returns
    -------
    tuple of float or None
        Channels in 0-1.
    """
    if index < 0 or index >= COUNT:
        return None
    start = index * 6
    chunk = _HEX[start : start + 6]
    return (
        int(chunk[0:2], 16) / 255.0,
        int(chunk[2:4], 16) / 255.0,
        int(chunk[4:6], 16) / 255.0,
    )


def name_for_index(index: int) -> str | None:
    """Return the name of a built-in colour index, or ``None``."""
    if index in SPECIAL:
        return SPECIAL[index]
    if index < 0 or index >= COUNT:
        return None
    return _table()[0][index]


def index_for_name(name: str) -> int | None:
    """Return the index of a named built-in colour, or ``None``.

    Case-insensitive, as ``cmd.color`` is.
    """
    return _table()[1].get(name.strip().lower())
